export function interestQuestions(interests: string[]): Record<string, NoulQuestion> {
  const out: Record<string, NoulQuestion> = {};
  interests.forEach((topic, i) => {
    out[`interest_${i}`] = noul(
      {
        topic,
        question: "Is `post.text` substantively about the subject named in `topic`?",
        focus: "The post must actually discuss or inform about the subject, not merely mention a related word.",
      },
      "The post's main content is about this subject, or a large part of it is",
      "The subject is absent, or only mentioned in passing",
    );
  });
  return out;
}

export function excludedTopicQuestions(topics: string[]): Record<string, NoulQuestion> {
  const out: Record<string, NoulQuestion> = {};
  topics.forEach((topic, i) => {
    out[`excluded_${i}`] = noul(
      {
        topic,
        question: "Is `post.text` primarily about, or primarily expressing, the thing described in `topic`?",
        focus:
          "Judge the post's main thrust. Read `topic` literally: if it names an attitude (e.g. 'hostility toward AI'), match posts expressing that attitude, not posts about the subject generally.",
      },
      "The post's main thrust matches `topic`",
      "The post is about something else, or touches `topic` only incidentally",
    );
  });
  return out;
}

// ---------------------------------------------------------------------------
// Code-side structural features, 0..1.
//
// CORROBORATE, NEVER DECIDE.
//
// Every one of these is a formatting convention, and formatting conventions are shared by
// slop merchants and by people with something to say. Measured on a live X timeline,
// twice: an industrial-automation post was hidden on hashtag_spam=1.00 alone, and a NASA
// thread was collapsed on thread_marker=1.00 alone. Both were correct detections of the
// format and wrong judgements of the post.
//
// The weights are all low enough that no structural feature can cross a hide threshold on
// its own. They only push a post a real signal has already implicated.
//
// Counting also belongs here rather than in a question: jev-1.13 does not count reliably,
// and a regex does it exactly and for free.
// ---------------------------------------------------------------------------

export const STRUCTURAL_WEIGHTS: Record<Platform, Record<string, number>> = {
  x: {
    thread_marker: 0.35, // "🧵", "1/12", "(1/n)"
    emoji_bullets: 0.3,
    staccato: 0.3,
    hashtag_spam: 0.2,
  },
  linkedin: {
    // "Broetry" — one short line per sentence — is a much stronger tell on LinkedIn than
    // the same shape is on X, where short posts are simply normal.
    staccato: 0.45,
    emoji_bullets: 0.35,
    hashtag_spam: 0.2,
  },
};

const THREAD_EMOJI = /\u{1F9F5}/u;

/** "1/12", "(3/7)", "2/n" — a position marker, as opposed to arithmetic. */
const POSITION_MARKER = /\(?\d{1,2}\s*\/\s*(\d{1,2}|n)\)?/;

/**
 * Emoji- or bullet-headed list lines.
 *
 * Deliberately does NOT match "1." or "- ". A numbered or dashed list is ordinary writing
 * — the sample set's own `enumerated_substance` case is exactly that — whereas a column of
 * ✅ / 🔥 / 👉 headers is the engagement-post shape. Measured: the earlier version scored
 * emoji_bullets 1.00 on "1. Install it / 2. Configure the key / 3. Run the tests".
 */
export const LEADING_EMOJI =
  /^\s*(?:[\u{1F300}-\u{1FAFF}\u{2190}-\u{21FF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE0F}\u{2022}\u{25AA}\u{25CF}\u{27A4}])\s*/u;

/**
 * A thread position marker, as opposed to a fraction, a date or an aspect ratio.
 *
 * Position markers sit at the START or END of a line — "1/12" opening a post, "3/7"
 * closing one. Arithmetic sits mid-sentence. Measured: the earlier
 * "digits-slash-digits anywhere" regex scored 1.00 on "we cut latency to 1/3 of what it
 * was", "shipping on 9/12 after the freeze lifts" and "render at 16/9 for the deck".
 */
function hasThreadMarker(text: string): boolean {
  if (THREAD_EMOJI.test(text)) return true;
  const tail = new RegExp(POSITION_MARKER.source + "$");
  return text.split("\n").some((line) => {
    const l = line.trim();
    if (!l) return false;
    const head = l.match(POSITION_MARKER);
    return (head !== null && head.index === 0) || tail.test(l);
  });
}

export function structuralSignals(text: string, platform: Platform): Record<string, number> {
  const lines = text
    .split(/\n+/)
    .map((l) => l.trim())
    .filter(Boolean);

  const bulleted = lines.filter((l) => LEADING_EMOJI.test(l)).length;
  const emoji_bullets = lines.length >= 3 ? ramp(bulleted / lines.length, 0.4, 0.8) : 0;

  let staccato = 0;
  if (lines.length >= 5) {
    const short = lines.filter((l) => l.length <= 60).length;
    staccato = ramp(short / lines.length, 0.6, 0.95);
  }

  const tags = (text.match(/(^|\s)#[A-Za-z0-9_]{2,}/g) ?? []).length;
  const hashtag_spam = ramp(tags, 2, 6);

  const out: Record<string, number> = { emoji_bullets, staccato, hashtag_spam };
  if (platform === "x") out.thread_marker = hasThreadMarker(text) ? 1 : 0;
  return out;
}

/** 0 at or below `lo`, 1 at or above `hi`, linear between. */
export function ramp(v: number, lo: number, hi: number): number {
  if (hi <= lo) return v > lo ? 1 : 0;
  return Math.max(0, Math.min(1, (v - lo) / (hi - lo)));
}

