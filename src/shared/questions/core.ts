/**
 * How the battery's three contributions combine into its own composite.
 *
 *   WORST  the single most damning signal (or structural feature). Dominant on purpose:
 *          a slop post usually trips ONE pattern hard. Measured on X, a rage-bait post
 *          scored rage_bait 0.96 with every other signal ~0.02, and the mean came out
 *          0.19 — indistinguishable from a good post.
 *   MEAN   broad slop character, for posts mildly bad in many ways at once.
 *   EMPTY  1 - substance. A nudge, not a verdict.
 *
 * EMPTY_MEDIA_DAMPING: on a post carrying media or a link, thin text is EXPECTED — the
 * content is the video or the article and the text is a caption. Measured on a live
 * timeline: a legitimate industrial-automation post scored substance 0.14 purely because
 * its text was a headline above a video.
 */
export const BLEND = { worst: 0.65, mean: 0.2, empty: 0.15 } as const;
export const EMPTY_MEDIA_DAMPING = 0.4;

/** How much the holistic Choice is worth against the whole battery. See VERDICT_CHOICE. */
export const VERDICT_BLEND = 0.6;

/**
 * The hard-signal rule ("any one of these disqualifies on its own") is not allowed to fire
 * when the holistic Choice confidently disagrees.
 *
 * The rule predates the holistic question and was written when the battery composite was
 * the only score. Measured on a live LinkedIn feed it hid a post at a composite of 0.30 —
 * far below the 0.64 hide threshold — purely because `engagement_bait` read 0.96, while
 * the holistic Choice said P(slop) = 0.06. That is a genuine call for help or a real
 * question that happens to be phrased like bait.
 *
 * One strong signal is still enough to hide a post, but not over a confident objection
 * from the better-separated judgment. Below this floor the composite decides on its own.
 */
export const HARD_SIGNAL_HOLISTIC_FLOOR = 0.35;
