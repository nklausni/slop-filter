// Signals, blending constants, and helpers shared by every platform.
//
// Design rules (from https://docs.typesafe.ai — see `Question design` in the README):
//  - one atomic judgment per question; combine in code
//  - phrase so a high noul means "this signal is PRESENT" (bad = true)
//  - literal wording; put boundary cases in criteria; keep counting/arithmetic in code
//  - all questions for one post go in ONE request (speculative fan-out is ~free)
//  - one post per request: items in a shared state contaminate each other
//
// What lives here is what is genuinely identical across X and LinkedIn. Anything whose
// wording has to change lives in the platform module, even when the idea is similar —
// jev-1.13 reads literally, so "a thread" and "the carousel in the comments" are not
// interchangeable just because both mean "withheld value".

import type { ChoiceQuestion, EntryType, NoulQuestion, Platform } from "../types.ts";

export interface Signal {
  /**
   * How damning this signal is at full confidence. The composite is driven by the WORST
   * single signal, not an average, so a weight of 1.0 means "certain of this alone is
   * certainly slop" and 0.3 means "this alone can never hide a post".
   */
  weight: number;
  question: NoulQuestion;
}

export type SignalSet = Record<string, Signal>;

/**
 * A Noul with explicit criteria on both sides.
 *
 * `yes`/`no` are EntryType, not string: the API accepts an object or array there, which
 * is how a `what` + `examples` shape pins down a subtle boundary.
 * See https://docs.typesafe.ai/primitives/advanced
 */
export function noul(instructions: NoulQuestion["instructions"], yes: EntryType, no: EntryType): NoulQuestion {
  return { type: "noul", instructions, criteria: { true: yes, false: no } };
}

